        /// <summary>
        /// The one hard safety check: NOTHING may exist in the approach band —
        /// not a collider, not a renderer, not an anchor — because that is where
        /// the throw camera lives. Same rule, and the same strictness, as
        /// AlleyGreyboxBuilder's approach check.
        /// </summary>
        private static void AuditApproachBand(ThunderLanesLayout L)
        {
            // The Y range is NOT floor-to-ceiling, and both ends are deliberate.
            // Bottom at 0.06 so the audit doesn't flag the floor slabs it just
            // laid (approach timber tops out at 0.02) — the floor is supposed to
            // be there. Top just under the ceiling so the ceiling plane at
            // exactly CeilingLanes doesn't false-positive: Bounds.Intersects
            // returns TRUE for merely touching bounds. Everything a camera could
            // actually hit lives between those two numbers.
            var band = new Bounds();
            band.SetMinMax(
                new Vector3(L.LaneBankXMin + AuditEpsilon, 0.06f, L.ApproachZMin + AuditEpsilon),
                new Vector3(L.LaneBankXMax - AuditEpsilon, L.CeilingLanes - 0.2f, -AuditEpsilon));

            int violations = 0;

            foreach (Collider c in CreatedColliders)
            {
                if (c == null || !band.Intersects(c.bounds)) continue;
                Debug.LogError($"[ThunderLanes] COLLIDER '{c.name}' is inside the approach band. " +
                               "Nothing may be built there — the throw camera lives in it.", c.gameObject);
                violations++;
            }

            foreach (Renderer r in CreatedRenderers)
            {
                if (r == null || !band.Intersects(r.bounds)) continue;
                Debug.LogError($"[ThunderLanes] RENDERER '{r.name}' is inside the approach band. A cosmetic box " +
                               "in the aim camera's face is as bad as a wall.", r.gameObject);
                violations++;
            }

            foreach (Transform a in CreatedAnchors)
            {
                if (a == null || !band.Contains(a.position)) continue;
                Debug.LogError($"[ThunderLanes] ANCHOR '{a.name}' is inside the approach band.", a.gameObject);
                violations++;
            }

            Report.Add(violations == 0
                ? "approach band: CLEAR (0 violations)"
                : $"approach band: {violations} VIOLATIONS — fix before playing");
        }

        private static void LogReport(ThunderLanesLayout L)
        {
            var sb = new StringBuilder();
            sb.AppendLine($"[ThunderLanes] built — {L.RoomWidth:F1}m x {L.RoomDepth:F1}m, " +
                          $"{CreatedColliders.Count} colliders, {CreatedAnchors.Count} anchors.");
            sb.AppendLine($"  ceilings: lanes {L.CeilingLanes} / concourse {L.CeilingConcourse} / " +
                          $"frontage {L.CeilingFrontage} / arcade {L.CeilingArcade}");
            foreach (string line in Report) sb.AppendLine("  " + line);
            sb.AppendLine("  These numbers are INFORMATION, not defects. Walk it before changing any of them.");
            Debug.Log(sb.ToString());
        }

