        /// <summary>
        /// Move the existing roaming Player to the new entrance. Without this the
        /// copied scene spawns you wherever the old venue put you, which in the
        /// new layout is usually inside a wall.
        /// </summary>
        private static void RehomePlayer(ThunderLanesLayout L)
        {
            var player = GameObject.Find("Player");
            if (player == null)
            {
                Debug.LogWarning("[ThunderLanes] No 'Player' object found — run " +
                                 "WeeSpurts > 3 Modify Open Scene > Set Up Roaming Player, then re-run this build.");
                return;
            }

            Transform spawn = null;
            foreach (Transform a in CreatedAnchors)
                if (a != null && a.name == "Anchor_PlayerSpawn") spawn = a;

            if (spawn == null) return;

            // A CharacterController overwrites direct transform writes on its next
            // step, so it has to go off around the teleport — same lesson
            // PlayerAvatar.MoveToThrowingStance already learned.
            var cc = player.GetComponent<CharacterController>();
            bool wasEnabled = cc != null && cc.enabled;
            if (wasEnabled) cc.enabled = false;
            player.transform.SetPositionAndRotation(spawn.position + Vector3.up * 0.1f, spawn.rotation);
            if (wasEnabled) cc.enabled = true;

            Debug.Log($"[ThunderLanes] Player moved to the entrance at {spawn.position}.");
        }

