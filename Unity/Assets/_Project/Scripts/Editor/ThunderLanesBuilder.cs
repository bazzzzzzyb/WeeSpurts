        /// <summary>
        /// Ceiling planes per zone. THE most important thing in this file for
        /// making the place read as a real building rather than extruded rooms —
        /// you feel the height change walking from the concourse into the arcade.
        /// All under one group so you can switch the lot off to work top-down.
        /// </summary>
        private static void BuildCeilings(GameObject root, ThunderLanesLayout L, Materials m)
        {
            var g = Group(root, "Ceilings");

            // FULL-WIDTH Z BANDS, edge to edge, no gaps. The first version gave
            // each zone a plane only as wide as that zone, which left holes you
            // could see the skybox through — a ceiling with gaps reads as
            // unfinished, not as zoning. Bands overlap at their seams on
            // purpose; from below you simply see the lower one.
            Cosmetic(g, "Ceil_Frontage", L.RoomXMin, L.RoomXMax, L.RoomZMin, L.FrontageZMax,
                     L.CeilingFrontage, 0.1f, m.Ceiling);
            Cosmetic(g, "Ceil_Concourse", L.RoomXMin, L.RoomXMax, L.FrontageZMax, L.ConcourseZMax,
                     L.CeilingConcourse, 0.1f, m.Ceiling);
            Cosmetic(g, "Ceil_Lanes", L.RoomXMin, L.RoomXMax, L.ConcourseZMax, L.PinsetterZMin,
                     L.CeilingLanes, 0.1f, m.Ceiling);
            Cosmetic(g, "Ceil_Pinsetter", L.RoomXMin, L.RoomXMax, L.PinsetterZMin, L.RoomZMax,
                     L.CeilingPinsetter, 0.1f, m.Ceiling);

            if (L.BuildArcade)
                Cosmetic(g, "Ceil_Arcade", L.LaneBankXMax + 1f, L.LaneBankXMax + 8f,
                         L.PitZMin, L.PitZMax, L.CeilingArcade, 0.1f, m.Ceiling);
        }

