        private static void BuildEntry(GameObject root, GameObject anchors, ThunderLanesLayout L, Materials m)
        {
            var g = Group(root, "Entry");
            float cx = L.RoomXMax - 3.5f;
            // 3.2 rather than 2.5 so the rotated jambs clear the pro shop's back
            // fitting — an angled object needs more room than its own footprint.
            float cz = L.FrontageZMin + 3.2f;

            // THE one angled element. Rotated so your first frame on entering is
            // a diagonal across the whole floor — lane bank receding one way,
            // bar neon the other. Set EntryAngleDegrees to 0 and the building
            // immediately goes back to reading as a box.
            var vest = Group(g, "Vestibule");
            SlabRotated(vest, "Mat", new Vector3(cx, 0.01f, cz), new Vector3(4.5f, 0.02f, 3.0f),
                        L.EntryAngleDegrees, m.StreetFloor, collider: false);
            SlabRotated(vest, "Jamb_L", new Vector3(cx - 1.6f, L.DoorHeight * 0.5f, cz - 1.4f),
                        new Vector3(0.4f, L.DoorHeight, 0.4f), L.EntryAngleDegrees, m.Wall, collider: true);
            SlabRotated(vest, "Jamb_R", new Vector3(cx + 1.6f, L.DoorHeight * 0.5f, cz - 1.4f),
                        new Vector3(0.4f, L.DoorHeight, 0.4f), L.EntryAngleDegrees, m.Wall, collider: true);

            Anchor(anchors, "Anchor_Entrance", cx, cz + 1.4f, 0f, L.EntryAngleDegrees + 180f);
            Anchor(anchors, "Anchor_PlayerSpawn", cx - 1.0f, cz + 2.6f, 0f, L.EntryAngleDegrees + 180f);

            Report.Add($"entry: vestibule rotated {L.EntryAngleDegrees}deg at x {cx:F1}, z {cz:F1}");
        }

