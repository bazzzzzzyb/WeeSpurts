        private static void BuildArcade(GameObject root, GameObject anchors, ThunderLanesLayout L, Materials m)
        {
            if (!L.BuildArcade) return;

            var g = Group(root, "Arcade");
            // South of the lane bank, level with the pit band — so it is the
            // FIRST thing glowing at you when you come through the doors and
            // step onto the street. An ALCOVE with its own mouth and its own
            // (low) ceiling; that drop is the whole effect.
            //
            // Deliberately NOT inside the concourse Z band: the street runs the
            // full 34m of the building and an alcove sitting in it would dam the
            // one route everybody uses.
            float x0 = L.LaneBankXMax + 1.0f;
            float x1 = L.LaneBankXMax + 8.0f;
            float z0 = L.PitZMin;
            float z1 = L.PitZMax;
            float t = L.WallThickness;

            // Alcove side walls, leaving a mouth on the street side.
            Slab(g, "Wall_W", x0 - t, x0, z0, z1 - 3.2f, 0f, L.CeilingArcade, m.Wall, true);
            Slab(g, "Wall_Back", x0 - t, x1, z0 - t, z0, 0f, L.CeilingArcade, m.Wall, true);

            // Cabinets down both walls, facing the aisle. The aisle is the clear
            // secondary route; the cabinets are what you stand at.
            int perSide = Mathf.Max(1, L.ArcadeCabinetCount / 2);
            for (int i = 0; i < perSide; i++)
            {
                float cz = z0 + 1.0f + i * (L.ArcadeCabinetWidth + 0.25f);
                Slab(g, $"Cab_W{i + 1}", x0 + 0.1f, x0 + 0.1f + L.ArcadeCabinetDepth,
                     cz, cz + L.ArcadeCabinetWidth, 0f, L.ArcadeCabinetHeight, m.Machine, true);
                Slab(g, $"Cab_E{i + 1}", x0 + 0.1f + L.ArcadeCabinetDepth + L.ArcadeAisleWidth,
                     x0 + 0.1f + 2f * L.ArcadeCabinetDepth + L.ArcadeAisleWidth,
                     cz, cz + L.ArcadeCabinetWidth, 0f, L.ArcadeCabinetHeight, m.Machine, true);
            }

            Anchor(anchors, "Anchor_Arcade", x0 + L.ArcadeCabinetDepth + L.ArcadeAisleWidth * 0.5f,
                   (z0 + z1) * 0.5f, 0f, 0f);

            Report.Add($"arcade: alcove x {x0:F1} .. {x1:F1}, ceiling {L.CeilingArcade}m " +
                       $"(vs {L.CeilingConcourse}m concourse — the drop IS the zoning), aisle {L.ArcadeAisleWidth}m");
        }

